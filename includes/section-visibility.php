            return [];
    }
}
/**
 * Global defaults live in the existing site settings catalog. Only an explicit
 * per-record override takes precedence. No catalog mutations are needed when
 * an admin toggles a global default.
 */
function gocamp_global_visibility(string $entity, string $key, bool $fallback): bool {
    static $settings = null;
    if ($settings === null) {
        $site_settings = [];
        $path = __DIR__ . '/../data/site_settings.php';
        if (is_file($path)) require $path;
        $settings = is_array($site_settings) ? $site_settings : [];
    }
    $globals = $settings['global_visibility'][$entity] ?? [];
    if (!is_array($globals) || !array_key_exists($key, $globals)) {
        return $fallback;
    }
    return filter_var($globals[$key], FILTER_VALIDATE_BOOLEAN);
}
function gocamp_visibility_override(array $record, string $key, string $entity = ''): ?bool {
    // New editor records have an authoritative override map: even an empty
    // map means inherit everything. This permits clearing old explicit values.
    if (array_key_exists('visibility_overrides', $record)) {
        $fields = $record['visibility_overrides'];
        if (!is_array($fields) || !array_key_exists($key, $fields)) return null;
        return filter_var($fields[$key], FILTER_VALIDATE_BOOLEAN);
    }
    $legacy = $record['section_visibility'] ?? [];
    if (!is_array($legacy) || !array_key_exists($key, $legacy)) return null;
    $value = filter_var($legacy[$key], FILTER_VALIDATE_BOOLEAN);
    if ($entity !== '') {
        $options = gocamp_visibility_options($entity);
        // Legacy values matching historical defaults were generated by the
        // old admin and do not prove an individual override. Only non-default
        // legacy values are retained as explicit decisions.
        if (isset($options[$key]) && $value === (bool)$options[$key][1]) {
            return null;
        }
    }
    return $value;
}
function gocamp_effective_visibility(array $record, string $entity, string $key, bool $default): bool {
    $override = gocamp_visibility_override($record, $key, $entity);
    return $override ?? gocamp_global_visibility($entity, $key, $default);
}
/**
 * Editors accept 'inherit', '1', or '0'. Missing/unsubmitted fields keep
 * existing overrides; this avoids accidental resets on partially posted forms.
 */
function gocamp_read_visibility_overrides($submitted, string $entity, array $previous = []): array {
    $result = $previous;
    if (!is_array($submitted)) return $result;
    foreach (gocamp_visibility_options($entity) as $key => $definition) {
        if (gocamp_gallery_disabled_by_policy($entity, $key)) continue;
        if (!array_key_exists($key, $submitted)) continue;
        $value = (string)$submitted[$key];
        if ($value === 'inherit') unset($result[$key]);
        elseif ($value === '0' || $value === '1') $result[$key] = $value === '1';
    }
    return $result;
}
function gocamp_section_visible(array $record, string $key, bool $default = true): bool {
    $visibility = $record['section_visibility'] ?? [];
    if (!is_array($visibility) || !array_key_exists($key, $visibility)) {
        return $default;
    }
    return filter_var($visibility[$key], FILTER_VALIDATE_BOOLEAN);
}
/**
 * Gallery display is disabled across destinations, program details and
 * program categories. Keep saved media paths for a future re-enable.
 */
function gocamp_gallery_disabled_by_policy(string $entity, string $key): bool {
    return ($entity === 'destination' && in_array($key, ['gallery', 'destination_gallery'], true))
        || ($entity === 'program' && $key === 'modal_gallery')
        || ($entity === 'category' && $key === 'gallery');
}
function gocamp_entity_section_visible(array $record, string $entity, string $key): bool {
    // Only this explicitly requested Soccer programme may display its new gallery.
    // All other programme, category and destination galleries remain disabled.
    if ($entity === 'program' && $key === 'modal_gallery' &&
        ($record['id'] ?? '') === 'uk-soccer-club-experience') {
        return !empty($record['gallery']) && gocamp_effective_visibility($record, $entity, $key, true);
    }
    if (gocamp_gallery_disabled_by_policy($entity, $key)) {
        return false;
    }
    $options = gocamp_visibility_options($entity);
    return gocamp_effective_visibility($record, $entity, $key, (bool)($options[$key][1] ?? true));
}
function gocamp_read_visibility($submitted, string $entity, array $previous = []): array {
    $result = $previous;
    $submitted = is_array($submitted) ? $submitted : [];
    foreach (gocamp_visibility_options($entity) as $key => $definition) {
        $result[$key] = isset($submitted[$key]) && (string)$submitted[$key] === '1';
    }
    return $result;
}
